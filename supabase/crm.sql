-- ---------- Saat ----------
create or replace function public.crm_simdi() returns timestamptz
language sql stable as $$ select now() $$;  -- tek kaynak; tarih karşılaştırması crm_bugun() ile

create or replace function public.crm_bugun() returns date
language sql stable as $$ select (public.crm_simdi() at time zone 'Europe/Istanbul')::date $$;

-- ---------- Yetki ----------
create table if not exists public.crm_sahip (
  user_id uuid primary key references auth.users(id) on delete cascade,
  eklenme timestamptz not null default public.crm_simdi()
);
alter table public.crm_sahip enable row level security;
-- crm_sahip'e istemciden erişim yok (politika yazılmadı); yalnız SQL Editor'den eklenir.

create or replace function public.crm_yetkili() returns boolean
language sql stable security definer set search_path to 'public' as $$
  select public.is_admin() and exists (select 1 from public.crm_sahip where user_id = auth.uid());
$$;

-- ---------- Telefon (03 §8) ----------
-- Ülke kodu ekler; boşluk/tire/parantez/nokta, "+" ve görünmez yön karakterlerini temizler.
-- Çözülemezse NULL döner (ham değer ayrıca saklanır, veri atılmaz).
create or replace function public.crm_telefon(p_raw text) returns text
language plpgsql immutable as $$
declare s text;
begin
  if p_raw is null then return null; end if;
  s := regexp_replace(p_raw, '[\s\-\(\)\.\+‎‏‪-‮⁦-⁩]', '', 'g');
  if s ~ '^90[2-5]\d{9}$' then return s;
  elsif s ~ '^0[2-5]\d{9}$' then return '9' || s;
  elsif s ~ '^[2-5]\d{9}$' then return '90' || s;
  elsif s ~ '^00[1-9]\d{7,14}$' then return substr(s, 3);       -- yurt dışı 00…
  end if;
  return null;
end $$;

