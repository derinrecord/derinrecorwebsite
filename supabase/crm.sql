-- ---------- Tetikleyiciler ----------
-- Firma: updated_at, aşama değişim zamanı, rakip sözleşmesi görevi (03 §4.4)
create or replace function public.crm_account_tetik() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  new.updated_at := public.crm_simdi();
  if tg_op = 'INSERT' then
    new.stage_changed_at := coalesce(new.stage_changed_at, public.crm_simdi());
    new.owner_user_id := coalesce(new.owner_user_id, auth.uid());
  elsif new.stage is distinct from old.stage then
    new.stage_changed_at := public.crm_simdi();
  end if;
  return new;
end $$;
drop trigger if exists crm_account_tetik on public.crm_account;
create trigger crm_account_tetik before insert or update on public.crm_account
  for each row execute function public.crm_account_tetik();

create or replace function public.crm_rakip_gorev() returns trigger
language plpgsql security definer set search_path to 'public' as $$
declare v_vade date; v_not text; v_id bigint;
begin
  if tg_op = 'UPDATE' and new.competitor_contract_ends_at is not distinct from old.competitor_contract_ends_at
     and new.current_software is not distinct from old.current_software then
    return new;
  end if;
  select task_id into v_id from public.crm_task
   where account_id = new.account_id and status = 'open' and source_kind = 'competitor_contract'
   order by task_id limit 1;
  if new.competitor_contract_ends_at is null then
    if v_id is not null then
      update public.crm_task set status = 'cancelled', updated_at = public.crm_simdi() where task_id = v_id;
    end if;
    return new;
  end if;
  v_vade := greatest(new.competitor_contract_ends_at - 45, public.crm_bugun());
  v_not := 'Rakip sözleşmesi ' || to_char(new.competitor_contract_ends_at, 'DD.MM.YYYY') || ' bitiyor'
           || coalesce(' (' || nullif(btrim(new.current_software), '') || ')', '') || ' — yenilemeden önce ara';
  if v_id is not null then
    update public.crm_task set due_date = v_vade, due_is_approx = true, priority = 'must', note = v_not,
           updated_at = public.crm_simdi() where task_id = v_id;
  else
    insert into public.crm_task(account_id, task_type, due_date, due_is_approx, priority, note, owner_user_id, source_kind)
    values (new.account_id, 'call', v_vade, true, 'must', v_not, coalesce(new.owner_user_id, auth.uid()), 'competitor_contract');
  end if;
  return new;
end $$;
drop trigger if exists crm_rakip_gorev on public.crm_account;
create trigger crm_rakip_gorev after insert or update on public.crm_account
  for each row execute function public.crm_rakip_gorev();

-- Kişi: telefon normalizasyonu, firma başına tek birincil
create or replace function public.crm_contact_tetik() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  new.updated_at := public.crm_simdi();
  new.phone_raw := nullif(btrim(new.phone_raw), '');
  new.phone_e164 := public.crm_telefon(new.phone_raw);
  if new.phone_raw is not null and new.phone_e164 is null then
    update public.crm_account set needs_review = true where account_id = new.account_id;
  end if;
  if new.is_primary and not new.is_deleted then
    update public.crm_contact set is_primary = false
     where account_id = new.account_id and is_primary and contact_id is distinct from new.contact_id;
  end if;
  return new;
end $$;
drop trigger if exists crm_contact_tetik on public.crm_contact;
create trigger crm_contact_tetik before insert or update on public.crm_contact
  for each row execute function public.crm_contact_tetik();

-- Görüşme: firmanın son temas zamanı (silmede geri alınmaz)
create or replace function public.crm_activity_tetik() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if tg_op = 'INSERT' then
    update public.crm_account
       set last_activity_at = greatest(coalesce(last_activity_at, '-infinity'::timestamptz), coalesce(new.occurred_at, public.crm_simdi()))
     where account_id = new.account_id;
  end if;
  return new;
end $$;
drop trigger if exists crm_activity_tetik on public.crm_activity;
create trigger crm_activity_tetik after insert on public.crm_activity
  for each row execute function public.crm_activity_tetik();

-- ---------- İç yardımcılar ----------
create or replace function public.crm_yetki_kontrol() returns void
language plpgsql stable as $$
begin
  if not public.crm_yetkili() then raise exception 'UnauthorizedAccess' using errcode = '42501'; end if;
end $$;

create or replace function public.crm_gorev_yaz(p_account bigint, p jsonb) returns bigint
language plpgsql as $$
declare v_id bigint; v_istek uuid := nullif(p->>'istek_id','')::uuid;
begin
  if p is null or p = 'null'::jsonb then return null; end if;
  if v_istek is not null then
    select task_id into v_id from public.crm_task where istek_id = v_istek;
    if v_id is not null then return v_id; end if;
  end if;
  if nullif(p->>'due_date','') is null then raise exception 'TaskDueDateRequired'; end if;
  insert into public.crm_task(account_id, contact_id, task_type, due_date, due_time, due_is_approx, due_label, priority, note, source_kind, istek_id)
  values (p_account, nullif(p->>'contact_id','')::bigint, coalesce(nullif(p->>'task_type',''),'call'),
          (p->>'due_date')::date, nullif(p->>'due_time','')::time, coalesce((p->>'due_is_approx')::boolean, false),
          nullif(btrim(p->>'due_label'),''), coalesce(nullif(p->>'priority',''),'normal'), nullif(btrim(p->>'note'),''),
          'manual', v_istek)
  returning task_id into v_id;
  return v_id;
end $$;

create or replace function public.crm_aktivite_yaz(p_account bigint, p jsonb) returns bigint
language plpgsql as $$
declare v_id bigint; v_istek uuid := nullif(p->>'istek_id','')::uuid; v_kisi bigint := nullif(p->>'contact_id','')::bigint;
begin
  if v_istek is not null then
    select activity_id into v_id from public.crm_activity where istek_id = v_istek;
    if v_id is not null then return v_id; end if;
  end if;
  if v_kisi is not null and not exists (select 1 from public.crm_contact where contact_id = v_kisi and account_id = p_account) then
    raise exception 'ContactNotInAccount';
  end if;
  insert into public.crm_activity(account_id, contact_id, activity_type, direction, outcome, occurred_at, summary, materials, offer_amount, offer_note, istek_id)
  values (p_account, v_kisi, coalesce(nullif(p->>'activity_type',''),'call'), coalesce(nullif(p->>'direction',''),'outbound'),
          nullif(p->>'outcome',''), coalesce(nullif(p->>'occurred_at','')::timestamptz, public.crm_simdi()),
          coalesce(p->>'summary',''), nullif(p->>'materials',''), nullif(p->>'offer_amount','')::numeric,
          nullif(btrim(p->>'offer_note'),''), v_istek)
  returning activity_id into v_id;
  return v_id;
end $$;

-- ---------- Uçlar (RPC) ----------
-- Görüşme ekle (+ isteğe bağlı sonraki görev) — TEK transaction (05 "activities")
create or replace function public.crm_aktivite_ekle(p jsonb) returns jsonb
language plpgsql as $$
declare v_acc bigint := (p->>'account_id')::bigint; v_act bigint; v_tsk bigint;
begin
  perform public.crm_yetki_kontrol();
  if not exists (select 1 from public.crm_account where account_id = v_acc and not is_deleted) then raise exception 'AccountNotFound'; end if;
  v_act := public.crm_aktivite_yaz(v_acc, p);
  v_tsk := public.crm_gorev_yaz(v_acc, p->'next_task');
  if p ? 'stage' and nullif(p->>'stage','') is not null then
    perform public.crm_asama(v_acc, p->>'stage', p->>'lost_reason', null);
  end if;
  return jsonb_build_object('activity_id', v_act, 'task_id', v_tsk);
end $$;

-- Görev tamamla: done + görüşme + (varsa) yeni görev — TEK transaction (03 §4.2)
create or replace function public.crm_gorev_tamamla(p_task bigint, p_aktivite jsonb, p_sonraki jsonb default null) returns jsonb
language plpgsql as $$
declare t public.crm_task%rowtype; v_act bigint; v_tsk bigint;
begin
  perform public.crm_yetki_kontrol();
  select * into t from public.crm_task where task_id = p_task for update;
  if not found then raise exception 'TaskNotFound'; end if;
  if t.status <> 'open' then raise exception 'TaskAlreadyClosed'; end if;
  v_act := public.crm_aktivite_yaz(t.account_id, coalesce(p_aktivite, '{}'::jsonb) || jsonb_build_object('contact_id', coalesce(p_aktivite->>'contact_id', t.contact_id::text)));
  update public.crm_task set status = 'done', done_at = public.crm_simdi(), done_activity_id = v_act, updated_at = public.crm_simdi()
   where task_id = p_task;
  v_tsk := public.crm_gorev_yaz(t.account_id, p_sonraki);
  if p_aktivite ? 'stage' and nullif(p_aktivite->>'stage','') is not null then
    perform public.crm_asama(t.account_id, p_aktivite->>'stage', p_aktivite->>'lost_reason', null);
  end if;
  return jsonb_build_object('activity_id', v_act, 'task_id', v_tsk);
end $$;

create or replace function public.crm_gorev_ekle(p_account bigint, p jsonb) returns bigint
language plpgsql as $$
begin
  perform public.crm_yetki_kontrol();
  return public.crm_gorev_yaz(p_account, p);
end $$;

-- Ertele (03 §4.3)
create or replace function public.crm_gorev_ertele(p_task bigint, p_tarih date, p_saat time default null, p_yaklasik boolean default false, p_etiket text default null) returns void
language plpgsql as $$
begin
  perform public.crm_yetki_kontrol();
  update public.crm_task set due_date = p_tarih, due_time = p_saat, due_is_approx = coalesce(p_yaklasik,false),
         due_label = nullif(btrim(p_etiket),''), snooze_count = snooze_count + 1, updated_at = public.crm_simdi()
   where task_id = p_task and status = 'open';
  if not found then
    if exists (select 1 from public.crm_task where task_id = p_task) then raise exception 'TaskAlreadyClosed'; end if;
    raise exception 'TaskNotFound';
  end if;
end $$;

create or replace function public.crm_gorev_iptal(p_task bigint) returns void
language plpgsql as $$
begin
  perform public.crm_yetki_kontrol();
  update public.crm_task set status = 'cancelled', updated_at = public.crm_simdi() where task_id = p_task and status = 'open';
end $$;

-- Aşama değiştir; "waiting" için açık görev zorunlu (03 §4.4)
create or replace function public.crm_asama(p_account bigint, p_stage text, p_kayip text default null, p_gorev jsonb default null) returns void
language plpgsql as $$
begin
  perform public.crm_yetki_kontrol();
  if p_stage not in ('new','contacted','followup','demo','profile','offer','onboarding','member','waiting','passive','lost') then
    raise exception 'InvalidStage';
  end if;
  if p_gorev is not null and p_gorev <> 'null'::jsonb then perform public.crm_gorev_yaz(p_account, p_gorev); end if;
  if p_stage = 'waiting' and not exists (select 1 from public.crm_task where account_id = p_account and status = 'open') then
    raise exception 'WaitingRequiresTask';
  end if;
  update public.crm_account set stage = p_stage,
         lost_reason = case when p_stage = 'lost' then coalesce(nullif(p_kayip,''), lost_reason) else lost_reason end
   where account_id = p_account and not is_deleted;
  if not found then raise exception 'AccountNotFound'; end if;
end $$;

-- Hızlı ekle: firma + isteğe bağlı ilk kişi (idempotent)
create or replace function public.crm_firma_ekle(p jsonb) returns bigint
language plpgsql as $$
declare v_id bigint; v_istek uuid := nullif(p->>'istek_id','')::uuid;
begin
  perform public.crm_yetki_kontrol();
  if v_istek is not null then
    select account_id into v_id from public.crm_account where istek_id = v_istek;
    if v_id is not null then return v_id; end if;
  end if;
  if nullif(btrim(p->>'name'),'') is null then raise exception 'AccountNameRequired'; end if;
  insert into public.crm_account(name, stage, heat, source, city, district, branches, organization_type, tags, notes, istek_id)
  values (btrim(p->>'name'), coalesce(nullif(p->>'stage',''),'new'), nullif(p->>'heat','')::smallint, nullif(p->>'source',''),
          nullif(btrim(p->>'city'),''), nullif(btrim(p->>'district'),''), nullif(p->>'branches',''),
          nullif(p->>'organization_type',''), nullif(p->>'tags',''), nullif(btrim(p->>'notes'),''), v_istek)
  returning account_id into v_id;
  if nullif(btrim(p->>'contact_name'),'') is not null or nullif(btrim(p->>'phone'),'') is not null then
    insert into public.crm_contact(account_id, name, role, phone_raw, is_primary)
    values (v_id, nullif(btrim(p->>'contact_name'),''), nullif(p->>'contact_role',''), p->>'phone', true);
  end if;
  return v_id;
end $$;

-- Mükerrer uyarısı (engel değil)
create or replace function public.crm_mukerrer(p_phone text default null, p_name text default null, p_haric bigint default null) returns jsonb
language plpgsql stable as $$
declare v_tel text := public.crm_telefon(p_phone); v jsonb;
begin
  perform public.crm_yetki_kontrol();
  select coalesce(jsonb_agg(distinct jsonb_build_object('account_id', a.account_id, 'name', a.name, 'stage', a.stage)), '[]'::jsonb) into v
    from public.crm_account a
    left join public.crm_contact c on c.account_id = a.account_id and not c.is_deleted
   where not a.is_deleted and (p_haric is null or a.account_id <> p_haric)
     and ((v_tel is not null and c.phone_e164 = v_tel)
       or (nullif(btrim(p_name),'') is not null and lower(a.name) = lower(btrim(p_name))));
  return v;
end $$;

-- Liste satırı (04 ②)
create or replace function public.crm_satir(a public.crm_account) returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'account_id', a.account_id, 'name', a.name, 'stage', a.stage, 'heat', a.heat, 'branches', a.branches,
    'city', a.city, 'owner_user_id', a.owner_user_id, 'tags', a.tags, 'needs_review', a.needs_review,
    'last_activity_at', a.last_activity_at, 'competitor_contract_ends_at', a.competitor_contract_ends_at,
    'primary_contact', (select jsonb_build_object('contact_id', c.contact_id, 'name', c.name, 'phone_e164', c.phone_e164, 'is_whatsapp', c.is_whatsapp)
                          from public.crm_contact c where c.account_id = a.account_id and not c.is_deleted
                          order by c.is_primary desc, c.sort_order, c.contact_id limit 1),
    'next_task', (select jsonb_build_object('task_id', t.task_id, 'due_date', t.due_date, 'due_time', t.due_time, 'due_is_approx', t.due_is_approx, 'task_type', t.task_type, 'priority', t.priority)
                    from public.crm_task t where t.account_id = a.account_id and t.status = 'open'
                    order by t.due_date, t.due_time nulls last limit 1));
$$;

-- Firmalar: filtre + sayfalama + sıralama (05 "Liste isteği")
create or replace function public.crm_firmalar(p jsonb default '{}'::jsonb) returns jsonb
language plpgsql stable as $$
declare
  v_bugun date := public.crm_bugun();
  v_sayfa int := greatest(coalesce((p->>'page')::int, 1), 1);
  v_boy int := least(greatest(coalesce((p->>'page_size')::int, 30), 1), 100);
  v_ara text := nullif(btrim(lower(p->>'search')), '');
  v_tel text := public.crm_telefon(p->>'search');
  v_toplam int; v_satirlar jsonb;
begin
  perform public.crm_yetki_kontrol();
  with f as (
    select a.* from public.crm_account a
     where not a.is_deleted
       and (p->'stages' is null or jsonb_array_length(p->'stages') = 0 or a.stage in (select jsonb_array_elements_text(p->'stages')))
       and (nullif(p->>'branch','') is null or (',' || coalesce(a.branches,'') || ',') like '%,' || (p->>'branch') || ',%')
       and (nullif(p->>'tag','') is null or (',' || coalesce(a.tags,'') || ',') like '%,' || (p->>'tag') || ',%')
       and (nullif(p->>'heat','') is null or a.heat = (p->>'heat')::smallint)
       and (nullif(p->>'city','') is null or lower(a.city) = lower(p->>'city'))
       and (nullif(p->>'owner_user_id','') is null or a.owner_user_id = (p->>'owner_user_id')::uuid)
       and (coalesce((p->>'needs_review')::boolean, false) = false or a.needs_review)
       and (nullif(p->>'untouched_days','') is null
            or a.last_activity_at is null
            or (a.last_activity_at at time zone 'Europe/Istanbul')::date < v_bugun - (p->>'untouched_days')::int)
       and (coalesce((p->>'no_open_task')::boolean, false) = false
            or not exists (select 1 from public.crm_task t where t.account_id = a.account_id and t.status = 'open'))
       and (nullif(p->>'competitor_within_days','') is null
            or (a.competitor_contract_ends_at is not null and a.competitor_contract_ends_at <= v_bugun + (p->>'competitor_within_days')::int))
       and (v_ara is null
            or lower(a.name) like '%' || v_ara || '%'
            or exists (select 1 from public.crm_contact c where c.account_id = a.account_id and not c.is_deleted
                        and (lower(coalesce(c.name,'')) like '%' || v_ara || '%'
                             or (v_tel is not null and c.phone_e164 = v_tel)
                             or regexp_replace(coalesce(c.phone_raw,''), '\D', '', 'g') like '%' || nullif(regexp_replace(v_ara, '\D', '', 'g'), '') || '%')))
  )
  , sirali as (
    select f.account_id, row_number() over (order by
            case when p->>'sort' = 'name' then lower(f.name) end,
            case when p->>'sort' = 'created' then f.created_at end desc,
            case when p->>'sort' = 'next_task' then (select min(t.due_date) from public.crm_task t where t.account_id = f.account_id and t.status = 'open') end nulls last,
            f.last_activity_at desc nulls last, f.account_id desc) as rn
      from f)
  select count(*)::int,
         coalesce(jsonb_agg(public.crm_satir(a) order by s.rn) filter (where s.rn > (v_sayfa-1)*v_boy and s.rn <= v_sayfa*v_boy), '[]'::jsonb)
    into v_toplam, v_satirlar
    from sirali s join public.crm_account a on a.account_id = s.account_id;
  return jsonb_build_object('toplam', v_toplam, 'sayfa', v_sayfa, 'sayfa_boyu', v_boy, 'satirlar', v_satirlar);
end $$;

-- Firma kartı: kişiler + açık görevler + son 20 görüşme
create or replace function public.crm_firma(p_account bigint) returns jsonb
language plpgsql stable as $$
declare a public.crm_account%rowtype;
begin
  perform public.crm_yetki_kontrol();
  select * into a from public.crm_account where account_id = p_account and not is_deleted;
  if not found then raise exception 'AccountNotFound'; end if;
  return jsonb_build_object(
    'firma', to_jsonb(a) - 'istek_id',
    'kisiler', coalesce((select jsonb_agg(to_jsonb(c) order by c.is_primary desc, c.sort_order, c.contact_id)
                           from public.crm_contact c where c.account_id = p_account and not c.is_deleted), '[]'::jsonb),
    'gorevler', coalesce((select jsonb_agg(to_jsonb(t) - 'istek_id' order by t.due_date, t.due_time nulls last)
                            from public.crm_task t where t.account_id = p_account and t.status = 'open'), '[]'::jsonb),
    'gorusmeler', coalesce((select jsonb_agg(x order by (x->>'occurred_at') desc nulls last, (x->>'activity_id')::bigint desc) from (
                              select to_jsonb(g) - 'istek_id' as x from public.crm_activity g
                               where g.account_id = p_account and not g.is_deleted
                               order by g.occurred_at desc nulls last, g.activity_id desc limit 20) q), '[]'::jsonb),
    'gorusme_sayisi', (select count(*) from public.crm_activity g where g.account_id = p_account and not g.is_deleted)
  );
end $$;

-- Ajanda: beş grup, tek sorgu kaynağı (03 §5). Ekran ve (Faz 4) günlük özet aynı fonksiyonu kullanır.
create or replace function public.crm_ajanda(p_ufuk int default 7, p_sahip uuid default null) returns jsonb
language plpgsql stable as $$
declare v_bugun date := public.crm_bugun(); v_ufuk int := case when p_ufuk in (7,30,90) then p_ufuk else 7 end;
begin
  perform public.crm_yetki_kontrol();
  return (
    with g as (
      select t.task_id, t.account_id, t.task_type, t.due_date, t.due_time, t.due_is_approx, t.due_label, t.priority, t.note,
             t.snooze_count, t.source_kind,
             a.name as account_name, a.stage as account_stage,
             k.contact_id, k.name as contact_name, k.phone_e164 as contact_phone_e164, k.is_whatsapp as contact_is_whatsapp
        from public.crm_task t
        join public.crm_account a on a.account_id = t.account_id and not a.is_deleted
        left join lateral (
          select c.contact_id, c.name, c.phone_e164, c.is_whatsapp from public.crm_contact c
           where not c.is_deleted and ((t.contact_id is not null and c.contact_id = t.contact_id)
                 or (t.contact_id is null and c.account_id = t.account_id))
           order by (c.contact_id = t.contact_id) desc nulls last, c.is_primary desc, c.sort_order, c.contact_id limit 1) k on true
       where t.status = 'open' and (p_sahip is null or t.owner_user_id = p_sahip)
    )
    select jsonb_build_object(
      'bugun', v_bugun, 'ufuk', v_ufuk,
      'gecikmis', coalesce((select jsonb_agg(to_jsonb(g) order by g.due_date, g.due_time nulls last) from g where g.due_date < v_bugun), '[]'::jsonb),
      'bugunku', coalesce((select jsonb_agg(to_jsonb(g) order by g.due_time nulls last, g.priority desc) from g where g.due_date = v_bugun), '[]'::jsonb),
      'hafta', coalesce((select jsonb_agg(to_jsonb(g) order by g.due_date, g.due_time nulls last) from g where g.due_date > v_bugun and g.due_date <= v_bugun + (v_ufuk - 1)), '[]'::jsonb),
      'firsatlar', coalesce((select jsonb_agg(public.crm_satir(a) order by a.competitor_contract_ends_at) from public.crm_account a
                              where not a.is_deleted and a.stage in ('new','contacted','followup','demo','profile','offer','waiting')
                                and a.competitor_contract_ends_at is not null and a.competitor_contract_ends_at <= v_bugun + 60
                                and (p_sahip is null or a.owner_user_id is null or a.owner_user_id = p_sahip)), '[]'::jsonb),
      'dokunulmamis', coalesce((select jsonb_agg(public.crm_satir(a) order by a.last_activity_at nulls first) from public.crm_account a
                              where not a.is_deleted and a.stage in ('contacted','followup','demo','profile','offer')
                                and (a.last_activity_at is null or (a.last_activity_at at time zone 'Europe/Istanbul')::date < v_bugun - 30)
                                and (p_sahip is null or a.owner_user_id is null or a.owner_user_id = p_sahip)), '[]'::jsonb)
    ));
end $$;

-- İstemciden çağrılabilecek fonksiyonlar: yalnız giriş yapmış kullanıcı (yetkiyi crm_yetkili() ayrıca denetler)
do $$
declare f text;
begin
  foreach f in array array[
    'crm_aktivite_ekle(jsonb)','crm_gorev_tamamla(bigint,jsonb,jsonb)','crm_gorev_ekle(bigint,jsonb)',
    'crm_gorev_ertele(bigint,date,time,boolean,text)','crm_gorev_iptal(bigint)','crm_asama(bigint,text,text,jsonb)',
    'crm_firma_ekle(jsonb)','crm_mukerrer(text,text,bigint)','crm_firmalar(jsonb)','crm_firma(bigint)','crm_ajanda(int,uuid)',
    'crm_yetkili()','crm_telefon(text)','crm_bugun()'] loop
    execute format('revoke execute on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  -- İç yardımcılar uçlar tarafından çağrıldığı için authenticated'da kalır; RLS yine geçerlidir.
  foreach f in array array['crm_gorev_yaz(bigint,jsonb)','crm_aktivite_yaz(bigint,jsonb)','crm_yetki_kontrol()','crm_satir(public.crm_account)','crm_simdi()'] loop
    execute format('revoke execute on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  foreach f in array array['crm_account_tetik()','crm_rakip_gorev()','crm_contact_tetik()','crm_activity_tetik()'] loop
    execute format('revoke execute on function public.%s from public, anon, authenticated', f);
  end loop;
end $$;

